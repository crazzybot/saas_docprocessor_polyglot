// Generates libs/ts-shared/src/generated/contracts.ts from contracts/schemas:
// for each schema, a TypeScript type and the schema itself (validated at
// runtime with Ajv). Run through `just contracts`; never edit the output.
//
//   node scripts/generate-ts-contracts.mjs [--check]
//
// --check exits 1 if the committed file is out of date.

import { readdir, readFile, writeFile } from 'node:fs/promises';
import process from 'node:process';
import { URL } from 'node:url';

import { compile } from 'json-schema-to-typescript';
import { format, resolveConfig } from 'prettier';

const SCHEMAS = new URL('../contracts/schemas/', import.meta.url);
const OUTPUT = new URL('../libs/ts-shared/src/generated/contracts.ts', import.meta.url);

/** `DocumentUploadedEvent` -> `documentUploadedEventSchema`. */
function schemaConstName(title) {
  return `${title[0].toLowerCase()}${title.slice(1)}Schema`;
}

let source =
  '/* Generated by scripts/generate-ts-contracts.mjs from contracts/schemas. Do not edit: run `just contracts`. */\n\n';
for (const file of (await readdir(SCHEMAS)).filter((name) => name.endsWith('.schema.json')).sort()) {
  const schema = JSON.parse(await readFile(new URL(file, SCHEMAS), 'utf8'));
  // Readers must ignore unknown fields, which the schemas allow; the types
  // still list only the known ones.
  const types = await compile(schema, schema.title, { bannerComment: '', additionalProperties: false, format: false });
  source += `// ${file}\n${types}\nexport const ${schemaConstName(schema.title)} = ${JSON.stringify(schema)} as const;\n\n`;
}

const formatted = await format(source, { ...(await resolveConfig(OUTPUT)), parser: 'typescript' });

if (process.argv.includes('--check')) {
  const current = await readFile(OUTPUT, 'utf8').catch(() => '');
  if (current !== formatted) {
    process.stderr.write(`${OUTPUT.pathname} is out of date: run \`just contracts\`\n`);
    process.exit(1);
  }
} else {
  await writeFile(OUTPUT, formatted);
}
