// Generates apps/web-ui/src/generated/api.ts, the web UI's types for the
// document service's HTTP API, from contracts/openapi.json. Run through
// `just contracts`; never edit the output.
//
//   node scripts/generate-web-client.mjs [--check]
//
// --check exits 1 if the committed file is out of date.

import { readFile, writeFile } from 'node:fs/promises';
import process from 'node:process';
import { URL } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';
import { format, resolveConfig } from 'prettier';

const INPUT = new URL('../contracts/openapi.json', import.meta.url);
const OUTPUT = new URL('../apps/web-ui/src/generated/api.ts', import.meta.url);

const ast = await openapiTS(INPUT);
const source =
  '/* Generated by scripts/generate-web-client.mjs from contracts/openapi.json. Do not edit: run `just contracts`. */\n\n' +
  astToString(ast);
const formatted = await format(source, { ...(await resolveConfig(OUTPUT)), parser: 'typescript' });

if (process.argv.includes('--check')) {
  const current = await readFile(OUTPUT, 'utf8').catch(() => '');
  if (current !== formatted) {
    process.stderr.write(`${OUTPUT.pathname} is out of date: run \`just contracts\`\n`);
    process.exit(1);
  }
} else {
  await writeFile(OUTPUT, formatted);
}
